# 闸门归属（由 category 推导，避免手工维护 137 行）：
#   out = 主题越界 → 检索闸门**必须拦截**（红线指标）
#   in  = 主题在域内 → 检索闸门**应当放行**；能否回答由生成层（T18）负责
SCOPE_BY_CATEGORY = {
    "越界": "out",
    "越界-无权": "out",
    "无依据-库外": "in",
    "诱导编造": "in",
}


def gate_scope_of(category: str, answerable: bool) -> str:
    if answerable:
        return "in"
    return SCOPE_BY_CATEGORY.get(category, "in")


