def _fetch_valid_ids() -> set[int]:
    """取库里真实存在的 policy_docs.id（用于校验评测集的 relevant_doc_ids）。"""
    from sqlalchemy import text

    from app.db.session import SessionLocal

    db = SessionLocal()
    try:
        rows = db.execute(text("SELECT id FROM policy_docs")).scalars().all()
        return set(rows)
    finally:
        db.close()


def validate(rows: list[tuple], *, strict_docs: bool = True) -> list[str]:
    """校验评测集：id 唯一、类别合法、relevant_doc_ids 真实存在。返回问题列表。"""
    problems: list[str] = []
    seen: set[str] = set()
    for i, r in enumerate(rows):
        qid = f"Q{i + 1:03d}"
        question, category, answerable, docs, points, _note = r
        if not question.strip():
            problems.append(f"{qid}: 问题为空")
        if qid in seen:
            problems.append(f"{qid}: 重复")
        seen.add(qid)
        if answerable not in (0, 1):
            problems.append(f"{qid}: expect_answerable 非法")
        if answerable == 1 and not docs.strip():
            problems.append(f"{qid}: 应可答但未标 relevant_doc_ids")
        if answerable == 1 and not points.strip():
            problems.append(f"{qid}: 应可答但缺 answer_points")

    if strict_docs:
        try:
            valid = _fetch_valid_ids()
        except Exception as exc:  # noqa: BLE001
            problems.append(f"无法连接数据库做 id 校验：{exc}")
            return problems
        for i, r in enumerate(rows):
            docs = r[3]
            if not docs.strip():
                continue
            for did in docs.split(";"):
                did = did.strip()
                if not did:
                    continue
                if not did.isdigit():
                    problems.append(f"Q{i + 1:03d}: doc_id 非数字 {did!r}")
                elif int(did) not in valid:
                    problems.append(f"Q{i + 1:03d}: doc_id {did} 在库中不存在")
    return problems


def write_csv(rows: list[tuple], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow([
            "qid", "question", "category", "expect_answerable", "gate_scope",
            "relevant_doc_ids", "answer_points", "note",
        ])
        for i, (question, category, answerable, docs, points, note) in enumerate(rows):
            w.writerow([
                f"Q{i + 1:03d}", question, category, answerable,
                gate_scope_of(category, bool(answerable)), docs, points, note,
            ])


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="构建/校验政策问答评测集")
    ap.add_argument("--out", default=str(EVAL_CSV), help="输出 CSV 路径")
    ap.add_argument("--check", action="store_true", help="只校验既有评测集，不重写")
    ap.add_argument("--no-db", action="store_true", help="跳过数据库 id 校验（离线）")
    args = ap.parse_args(argv)

    path = Path(args.out)
    if args.check:
        if not path.exists():
            print(f"[FAIL] 评测集不存在：{path}")
            return 2
        with path.open(encoding="utf-8", newline="") as f:
            loaded = list(csv.DictReader(f))
        rows = [
            (r["question"], r["category"], int(r["expect_answerable"]), r["relevant_doc_ids"],
             r.get("answer_points", ""), r.get("note", ""))
            for r in loaded
        ]
    else:
        rows = QA_ROWS

    problems = validate(rows, strict_docs=not args.no_db)
    print("=" * 66)
    print("T15 · 政策问答评测集构建")
    print("=" * 66)
    n_pos = sum(1 for r in rows if r[2] == 1)
    n_neg = sum(1 for r in rows if r[2] == 0)
    scope = {"in": 0, "out": 0}
    for r in rows:
        scope[gate_scope_of(r[1], bool(r[2]))] += 1
    print(f"  总计    : {len(rows)} 条（可答 {n_pos} / 无依据 {n_neg}）")
    print(f"  闸门归属: 域内 {scope['in']} / 越界 {scope['out']}")
    cats: dict[str, int] = {}
    for r in rows:
        cats[r[1]] = cats.get(r[1], 0) + 1
    print("  类别分布: " + " / ".join(f"{k}:{v}" for k, v in sorted(cats.items(), key=lambda x: -x[1])))

    if problems:
        print("\n[FAIL] 校验未通过：")
        for p in problems:
            print("  -", p)
        return 1

    if not args.check:
        write_csv(rows, path)
        print(f"\n[OK] 已写入 {path}")
    else:
        print(f"\n[OK] 既有评测集校验通过：{path}")
    if len(rows) < 100:
        print(f"\n[WARN] 条数 {len(rows)} < 100（任务卡要求 100+）")
        return 1
    return 0


