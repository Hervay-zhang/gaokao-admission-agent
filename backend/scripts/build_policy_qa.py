"""T15 · 政策问答评测集构建器（→ data/eval/policy_qa.csv）。

评测集结构（每行一条 QA）
------------------------
| 字段 | 含义 |
|---|---|
| ``qid`` | 评测条编号（稳定，便于复跑对比） |
| ``question`` | 用户问题（口语化，模拟真实提问） |
| ``category`` | 类别：志愿填报 / 报名 / … / 越界 / 无依据-库外 / 诱导编造 |
| ``expect_answerable`` | ``1`` = 库内有依据应答；``0`` = 库内无依据（应走兜底/拒答） |
| ``gate_scope`` | **期望的闸门归属**：``in`` = 主题在域内（检索闸门**应当放行**）；``out`` = 主题越界（检索闸门**应当拦截**） |
| ``relevant_doc_ids`` | 相关文档 id（分号分隔；来自**真实** ``policy_docs``）；无依据条留空 |
| ``answer_points`` | 标准答案要点（**仅评测用**，不入产品库；供 LLM-as-judge 对照） |
| ``note`` | 备注 |

**⚠️ 重要的架构分层（勿混）**

评测集把「无依据」细分为两类，**它们由不同的机制负责**：

1. **`gate_scope=out`（越界）**：天气/地理/娱乐/编程/生活服务等**主题不在域内**。
   → 由 **检索闸门**（T14 `term_coverage` + IDF）拦截，**不调用 LLM** → 兜底。
   → 这是本卡要验证的核心指标 `out_scope_block`。
2. **`gate_scope=in`（域内但未收录 / 诱导编造）**：问题**主题在域内**（如「高考报名总人数」
   「清华大学录取线」），检索确实命中相关政策文档，但**文档并不包含该具体事实**。
   → 检索闸门**应当放行**（文档确实主题相关）；「这一段依据能否支撑该问题」由**生成层**判断
     （T18 后置校验：无支撑则回落兜底 / 标记疑似编造）。
   → 本卡只记录 `in_domain_fallback` 作为**参考指标**（不设硬基线，待 T18 补齐后转硬）。

红线
----
- 评测集**只落 ``data/eval/``**，**不写 MySQL**（与产品库物理隔离）；
- ``relevant_doc_ids`` 必须来自**真实存在的** ``policy_docs.id``（构建时校验，不存在即报错退出）；
- ``answer_points`` 必须能在对应文档正文中找到依据（不编造标准答案）。

用法
----
    cd backend && ./.venv/Scripts/python.exe scripts/build_policy_qa.py
    cd backend && ./.venv/Scripts/python.exe scripts/build_policy_qa.py --check   # 只校验既有评测集
"""

