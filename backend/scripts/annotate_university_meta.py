def strip_parens(name: str) -> str:
    """去掉括号后缀 → 基础校名。"""
    import re
    out = name
    while "(" in out or "（" in out:
        out = re.sub(r"[（(][^（）()]*[）)]", "", out)
    return out.strip() or name


def match_tags(base: str) -> str:
    """按基础校名匹配 985/211/双一流。"""
    tags: list[str] = []
    if base in TAG_985:
        tags.append("985")
    if base in TAG_211:
        tags.append("211")
    if base in TAG_SYL:
        tags.append("双一流")
    return "|".join(tags)


def guess_province(code: int, name: str, base: str) -> str:
    """省份推断：校区覆盖表 → 校名前缀关键词 → 空。"""
    if code in PROVINCE_BY_CODE:
        return PROVINCE_BY_CODE[code]
    for prefix, prov in PROVINCE_PREFIX:
        if name.startswith(prefix) or base.startswith(prefix):
            return prov
    return ""


def guess_type(base: str) -> str:
    """类型推断：关键词优先，兜底综合。"""
    for keys, stype in TYPE_KEYWORDS:
        for k in keys:
            if k in base:
                return stype
    return ""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="院校元数据标注（985/211/双一流 + 省份 + 类型）")
    parser.add_argument("--report", action="store_true", help="只报告不写回")
    args = parser.parse_args(argv)

    if not UNIVERSITIES.exists():
        print(f"✗ 未找到 {UNIVERSITIES}", file=sys.stderr)
        return 1

    with UNIVERSITIES.open("r", encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))

    fields = list(rows[0].keys()) if rows else []
    changed = {"tags": 0, "province": 0, "school_type": 0, "status": 0}

    for r in rows:
        code = int(r["university_code"])
        name = r["university_name"]
        base = r["base_name"] or strip_parens(name)

        # tags：仅当为空时补（保护已核）
        if not r["tags"].strip():
            t = match_tags(base)
            if t:
                r["tags"] = t
                changed["tags"] += 1

        # province：仅当为空时补
        if not r["province"].strip():
            p = guess_province(code, name, base)
            if p in PROVINCES:
                r["province"] = p
                changed["province"] += 1

        # school_type：仅当为空时补
        if not r["school_type"].strip():
            st = guess_type(base)
            if st:
                r["school_type"] = st
                changed["school_type"] += 1

        # meta_status：province + school_type 齐全 → 已核
        new_status = "已核" if (r["province"].strip() and r["school_type"].strip()) else "待补"
        if new_status != r["meta_status"]:
            r["meta_status"] = new_status
            changed["status"] += 1

    # 统计
    annotated = sum(1 for r in rows if r["meta_status"] == "已核")
    print("=" * 60)
    print("院校元数据标注")
    print("=" * 60)
    print(f"总数 {len(rows)} 所")
    print(f"  补 tags       : {changed['tags']}")
    print(f"  补 province   : {changed['province']}")
    print(f"  补 school_type: {changed['school_type']}")
    print(f"  状态变更       : {changed['status']}")
    print(f"已核 {annotated} / 待补 {len(rows) - annotated}")

    if args.report:
        print("（--report 模式，未写回）")
        return 0

    with UNIVERSITIES.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    print(f"✅ 已写回 {UNIVERSITIES.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
