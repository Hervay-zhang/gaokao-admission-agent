def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="社区种子数据（幂等，可 --force 重灌）")
    parser.add_argument("--force", action="store_true", help="清空社区四表后重灌")
    args = parser.parse_args()

    db = SessionLocal()
    try:
        # 幂等保护
        existing = db.query(ForumPost.id).count()
        if existing and not args.force:
            print(f"forum_posts 已有 {existing} 条数据，未指定 --force，跳过写入。")
            print("如需清空重灌请运行: python scripts/seed_community.py --force")
            return

        if args.force:
            # 按外键顺序清空
            db.query(ForumPostFavorite).delete()
            db.query(ForumPostLike).delete()
            db.query(ForumComment).delete()
            db.query(ForumPost).delete()
            db.flush()
            print("已清空论坛四张表，开始写入种子数据…")

        now = datetime.now()
        post_ids: list[int] = []
        comment_id_maps: dict[int, list[int]] = {}
        like_count_map: dict[int, int] = {}
        fav_count_map: dict[int, int] = {}

        # ---- 1) 帖子 ----
        for p in POSTS:
            sid, _nick = USERS[p["author"]]
            created = now - timedelta(days=p["age_days"], hours=p["age_hours"])
            post = ForumPost(
                title=p["title"],
                content=p["content"],
                category=p["category"],
                author_sid=sid,
                author_nickname=nick(sid),
                like_count=0,
                comment_count=len(p["comments"]),
                view_count=p["view"],
                is_pinned=p["pinned"],
                is_removed=False,
                created_at=created,
                updated_at=created,
            )
            db.add(post)
            db.flush()
            post_ids.append(post.id)
            comment_id_maps[post.id] = []

        # ---- 2) 评论（含回复关系）----
        for p, post_id in zip(POSTS, post_ids, strict=False):
            comment_rows: list[int] = []
            for i, c in enumerate(p["comments"]):
                sid, _nick = USERS[c["author"]]
                reply_to_id = None
                reply_to_nickname = None
                if c.get("reply") is not None:
                    target = p["comments"][c["reply"]]
                    target_sid, _ = USERS[target["author"]]
                    reply_to_nickname = nick(target_sid)
                    # 评论时间递增，取距帖子创建的偏移
                created = now - timedelta(
                    days=p["age_days"],
                    hours=p["age_hours"],
                ) + timedelta(
                    hours=2 + i * 5 + random.randint(0, 4),
                    minutes=random.randint(0, 59),
                )
                if created >= now:
                    created = now - timedelta(minutes=random.randint(1, 45))
                comment = ForumComment(
                    post_id=post_id,
                    content=c["content"],
                    author_sid=sid,
                    author_nickname=nick(sid),
                    like_count=c.get("like", 0),
                    reply_to_id=reply_to_id,
                    reply_to_nickname=reply_to_nickname,
                    is_removed=False,
                    created_at=created,
                )
                db.add(comment)
                db.flush()
                comment_rows.append(comment.id)
            comment_id_maps[post_id] = comment_rows

        # ---- 3) 点赞（避开作者本人，保证唯一）----
        for p, post_id in zip(POSTS, post_ids, strict=False):
            author_sid, _ = USERS[p["author"]]
            candidates = [s for s in USER_SIDS if s != author_sid]
            k = random.randint(3, 11)
            chosen = random.sample(candidates, k=min(k, len(candidates)))
            like_count_map[post_id] = len(chosen)
            for sid in chosen:
                created = now - timedelta(
                    days=random.randint(0, max(1, p["age_days"])),
                    hours=random.randint(0, 20),
                )
                db.add(ForumPostLike(post_id=post_id, user_sid=sid, created_at=created))

        # ---- 4) 收藏（避开作者本人，保证唯一）----
        for p, post_id in zip(POSTS, post_ids, strict=False):
            author_sid, _ = USERS[p["author"]]
            candidates = [s for s in USER_SIDS if s != author_sid]
            k = random.randint(0, 6)
            chosen = random.sample(candidates, k=min(k, len(candidates)))
            fav_count_map[post_id] = len(chosen)
            for sid in chosen:
                created = now - timedelta(
                    days=random.randint(0, max(1, p["age_days"])),
                    hours=random.randint(0, 20),
                )
                db.add(ForumPostFavorite(post_id=post_id, user_sid=sid, created_at=created))

        # ---- 5) 同步冗余计数 ----
        for post_id, like_cnt in like_count_map.items():
            db.query(ForumPost).filter(ForumPost.id == post_id).update(
                {"like_count": like_cnt}
            )

        db.commit()

        # ---- 统计 ----
        total_comments = sum(len(p["comments"]) for p in POSTS)
        total_likes = sum(like_count_map.values())
        total_favs = sum(fav_count_map.values())
        print(f"写入完成：帖子 {len(post_ids)} 条，评论 {total_comments} 条，"
              f"点赞 {total_likes} 条，收藏 {total_favs} 条。")
        print("板块分布: ", end="")
        from collections import Counter
        dist = Counter(p["category"] for p in POSTS)
        print(dict(dist))
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()
